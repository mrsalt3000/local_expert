def _key(text: str) -> str:
    return re.sub(r"[^0-9a-zа-яё]+", " ", text.casefold()).strip()


def _alias_map() -> dict[str, str]:
    mapping: dict[str, str] = {}
    for topic in TOPICS:
        mapping[_key(topic)] = topic
        for alias in _ALIASES.get(topic, ()):
            mapping.setdefault(_key(alias), topic)
    return mapping


_ALIAS_BY_KEY = _alias_map()
_TOPIC_ORDER = {topic: index for index, topic in enumerate(TOPICS)}


def normalize_topics(values: Iterable[str] | None) -> tuple[str, ...]:
    """Оставляет известные темы, убирает дубли и ограничивает их число."""
    if not values:
        return ()
    found: set[str] = set()
    for value in values:
        if not isinstance(value, str):
            continue
        canonical = _ALIAS_BY_KEY.get(_key(value))
        if canonical is not None:
            found.add(canonical)
    ordered = sorted(found, key=lambda topic: _TOPIC_ORDER[topic])
    return tuple(ordered[:MAX_TOPICS_PER_BOOK])


def parse_topics_json(raw: str | None) -> tuple[str, ...]:
    """Читает JSON-массив тем из каталога; битые данные не роняют API."""
    if not raw:
        return ()
    try:
        payload = json.loads(raw)
    except (TypeError, ValueError):
        return ()
    if not isinstance(payload, list):
        return ()
    return normalize_topics(payload)


def topics_to_json(topics: Iterable[str] | None) -> str:
    return json.dumps(list(normalize_topics(topics)), ensure_ascii=False)


